import assert from 'node:assert/strict';
import { createActionQueue } from '../dist/simulation-input.mjs';
const queue = createActionQueue();
const dispatched = [];
queue.push('KeyQ');
queue.push('Space');
queue.push('Space', true);
queue.push('KeyW');
assert.deepEqual(dispatched, []);
queue.drain(code => dispatched.push(code));
assert.deepEqual(dispatched, ['KeyQ', 'Space']);
queue.drain(code => dispatched.push(code));
assert.equal(dispatched.length, 2);
queue.push('KeyF');
queue.clear();
queue.drain(() => assert.fail('stale action after pause'));
queue.push('KeyX');
queue.drain(() => queue.push('KeyQ'));
const later = [];
queue.drain(code => later.push(code));
assert.deepEqual(later, ['KeyQ']);
console.log('Simulation input: ordered edges, repeat filtering, pause clearing passed');
