import assert from 'node:assert/strict';
import {teamKey,playerKey,formationSlots,emptyLineups,setLineup,applyLineups,emptyTransfers,setTransfer,applyTransfers,validateLineups} from '../dist/editor/roster-layout.mjs';
const rom=(t,s,name)=>({name,rom_origin_team_id:t,rom_origin_slot:s,shirt_number:s+1,position:s===0?'GK':'MF'});
const custom={id:'custom:brzk-fc',name:'BRZK FC',custom:true,players:[{id:'custom:jose',name:'Jose',position:'FW',shirt_number:9}]};
const source={teams:[{id:0,name:'A',players:Array.from({length:20},(_,s)=>rom(0,s,'A'+s)),formation:{label:'4-4-2',outfield_slots:[]}},{id:1,name:'B',players:Array.from({length:20},(_,s)=>rom(1,s,'B'+s)),formation:{label:'4-4-2',outfield_slots:[]}},custom]};
assert.equal(formationSlots('4-2-3-1').length,10);
let transfers=setTransfer(emptyTransfers(),'rom:0:3','custom:brzk-fc');
transfers=setTransfer(transfers,'custom:jose','rom:1');
const moved=applyTransfers(source,transfers);
assert.equal(moved.teams[0].players.length,19);
assert.equal(moved.teams[1].players.length,21);
assert.equal(moved.teams[2].players.some(p=>playerKey(p)==='rom:0:3'),true);
assert.equal(moved.teams[2].players.some(p=>playerKey(p)==='custom:jose'),false);
assert.equal(source.teams[0].players.length,20,'source catalog stays untouched');
let formation=setLineup(emptyLineups(),1,'4-3-3',Array.from({length:11},(_,s)=>'rom:1:'+s));
const applied=applyLineups(moved,formation);
assert.equal(applied.teams[1].formation.label,'4-3-3');
assert.equal(applied.teams[1].formation.outfield_slots.length,10);
assert.equal(applied.teams[1].players[0].rom_origin_slot,0);
assert.equal(applied.teams[2].players.length,11,'small squads get temporary match actors');
assert.throws(()=>setLineup(emptyLineups(),0,'9-1',['rom:0:0']));
assert.throws(()=>setLineup(emptyLineups(),0,'4-4-2',['rom:0:0','rom:0:0']));
assert.throws(()=>validateLineups({schema_version:1,teams:[{team_id:'rom:0',formation:'4-4-2',starters:['bad']}]}));
console.log('OK: transferencias entre clubes, identidade, titulares, quatro formacoes e fallback');
