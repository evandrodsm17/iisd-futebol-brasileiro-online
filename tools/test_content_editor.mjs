import assert from 'node:assert/strict';
import {createEmptyPackage,defaultKits,validateContentPackage,contentId,customCatalogTeams,customStadiums,assetPath} from '../dist/editor/content-model.mjs';
import {writeContentZip,readContentZip,crc32} from '../dist/editor/content-zip.mjs';
const model=createEmptyPackage();
model.stadiums.push({id:'arena-nova',name:'Arena Nova',layout_id:1,image:'assets/arena.png'});
model.assets.push('assets/arena.png','assets/escudo.png');
model.clubs.push({id:'brzk-fc',name:'BRZK FC',city:'Salvador',country:'Brasil',crest:'assets/escudo.png',stadium_id:'arena-nova',kits:defaultKits()});
model.players.push({id:'atleta-1',club_id:'brzk-fc',name:'Atleta Teste',position:'FW',shirt_number:9,overall:77});
assert.equal(validateContentPackage(model),model);
assert.equal(contentId('Atlético-MG'),'atletico-mg');
assert.equal(assetPath('../bad.png'),false);
const teams=customCatalogTeams(model);
assert.equal(teams[0].id,'custom:brzk-fc');
assert.equal(teams[0].players.length,11);
assert.equal(teams[0].players[0].shirt_number,9);
assert.equal(teams[0].kit.home.shirt[0],'#147D86');
const layouts=[{id:1,name:'USA',asset:'stadium.png',crop:{x:1,y:2,w:3,h:4}}];
assert.equal(customStadiums(model,layouts,()=>'/blob/arena')[0].asset,'/blob/arena');
function bad(edit){const input=structuredClone(model);edit(input);assert.throws(()=>validateContentPackage(input));}
bad(p=>p.players[0].club_id='missing');
bad(p=>p.clubs[0].kits.pop());
bad(p=>p.clubs[0].kits[0].colours.shirt='blue');
bad(p=>p.clubs[0].crest='../escape.png');
bad(p=>p.stadiums[0].layout_id=8);
const asset=new Uint8Array([137,80,78,71,13,10,26,10]);
const zip=writeContentZip([{name:'content-package.json',bytes:new TextEncoder().encode(JSON.stringify(model))},{name:'assets/escudo.png',bytes:asset}]);
const unpacked=await readContentZip(zip);
assert.deepEqual(unpacked.get('assets/escudo.png'),asset);
assert.equal(JSON.parse(new TextDecoder().decode(unpacked.get('content-package.json'))).package_id,model.package_id);
assert.equal(crc32(new TextEncoder().encode('123456789')),0xcbf43926);
await assert.rejects(readContentZip(new Blob(['not-zip'])),/ZIP/);
assert.throws(()=>writeContentZip([{name:'../escape',bytes:asset}]),/proibido/);
console.log('Content editor schema, catalog adapter and ZIP: OK');
